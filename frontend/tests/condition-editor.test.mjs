import test from "node:test";
import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { createServer } from "vite";

const leaf = (key) => ({ operator: "EQUALS", field_key: key, value: true });
const group = (operator, ...conditions) => ({ operator, conditions });
const fields = ["A", "B", "C", "D"].map((key) => ({ id: key, field_key: key, label: key, field_type: "BOOLEAN", config: {} }));

test("nested condition editor keeps AST, edits one branch, and evaluates both expressions", async () => {
  const dom = new JSDOM("<!doctype html><html><body><div id='root'></div></body></html>", { url: "http://localhost/templates" });
  const globals = { window: dom.window, document: dom.window.document, navigator: dom.window.navigator, HTMLElement: dom.window.HTMLElement, Node: dom.window.Node, IS_REACT_ACT_ENVIRONMENT: true };
  const previous = Object.fromEntries(Object.keys(globals).map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)]));
  for (const [key, value] of Object.entries(globals)) Object.defineProperty(globalThis, key, { configurable: true, writable: true, value });
  const server = await createServer({ server: { middlewareMode: true }, appType: "custom", logLevel: "silent" });
  const { ConditionEditor } = await server.ssrLoadModule("/src/TemplateAdmin.tsx");
  const { conditionError, conditionStats } = await server.ssrLoadModule("/src/conditionTree.ts");
  const { evaluateCondition } = await server.ssrLoadModule("/src/conditions.ts");
  const React = await import("react");
  const { act } = React;
  const { createRoot } = await import("react-dom/client");
  const root = createRoot(dom.window.document.getElementById("root"));
  let current = null;
  // Keep the change callback stable so every click re-renders the edited tree.
  const changed = next => { current = next; root.render(React.createElement(ConditionEditor, { title: "Тест", value: current, fields, change: changed })); };
  const show = async next => { current = next; await act(async () => root.render(React.createElement(ConditionEditor, { title: "Тест", value: current, fields, change: changed }))); };
  const click = async button => { assert.ok(button); await act(async () => button.click()); };
  const select = async (element, value) => { await act(async () => { element.value = value; element.dispatchEvent(new dom.window.Event("change", { bubbles: true })); }); };
  try {
    const first = group("AND", group("OR", leaf("A"), leaf("B")), leaf("C"), leaf("D"));
    await show(first);
    assert.deepEqual(current, first, "opening an existing nested rule changes nothing");
    assert.equal(dom.window.document.querySelectorAll(".condition-group").length, 2);
    assert.match(dom.window.document.querySelector(".condition-preview").textContent, /A равно true ИЛИ B равно true/);
    assert.equal(evaluateCondition(current, { A: false, B: true, C: true, D: true }), true);
    assert.equal(evaluateCondition(current, { A: false, B: false, C: true, D: true }), false);
    const fourthLeaf = dom.window.document.querySelectorAll(".condition-leaf")[3];
    await select(fourthLeaf.querySelector("select"), "A");
    assert.deepEqual(current.conditions[0], first.conditions[0], "editing D does not change the OR branch");
    assert.equal(current.conditions[2].field_key, "A");
    await show(group("AND", group("OR", leaf("A"), group("AND", leaf("B"), leaf("C"))), leaf("D")));
    assert.equal(dom.window.document.querySelectorAll(".condition-group").length, 3);
    assert.equal(evaluateCondition(current, { A: false, B: true, C: true, D: true }), true);
    assert.equal(evaluateCondition(current, { A: false, B: true, C: false, D: true }), false);
    const before = structuredClone(current);
    await select(dom.window.document.querySelector(".condition-group select"), "OR");
    assert.deepEqual(current.conditions[0], before.conditions[0], "other nested branches stay intact");
    await show(before);
    const inner = dom.window.document.querySelectorAll(".condition-group")[2];
    await click(inner.querySelector(".condition-negate input"));
    assert.equal(current.conditions[0].conditions[1].operator, "NOT");
    assert.equal(evaluateCondition(current, { A: false, B: true, C: true, D: true }), false);
    assert.equal(evaluateCondition(current, { A: false, B: true, C: false, D: true }), true);
    await show(group("AND", leaf("A"), leaf("B")));
    await click(dom.window.document.querySelector(".condition-editor > .condition-group > .condition-group-actions button:nth-child(2)"));
    assert.equal(current.conditions[2].operator, "AND", "UI adds a nested group");
    assert.equal(current.conditions[2].conditions.length, 2);
    assert.ok(conditionError(current, fields), "new blank leaves must be filled before save");
    assert.equal(conditionError(group("AND", leaf("A")), fields), "В группе должно быть минимум два условия.");
    assert.equal(conditionError(group("AND", leaf("A"), leaf("A")), fields, "A"), "Вопрос не может зависеть от самого себя.");
    let deep = leaf("A");
    for (let i = 0; i < 7; i++) deep = { operator: "NOT", condition: deep };
    assert.equal(conditionStats(deep).depth, 8);
    assert.match(conditionError({ operator: "NOT", condition: deep }, fields), /Глубина/);
    assert.match(conditionError(group("AND", ...Array.from({ length: 100 }, () => leaf("A"))), fields), /100 элементов/);
    assert.equal(conditionError(group("AND", leaf("A"), leaf("B")), fields), null, "existing flat rules remain valid");
    const setLeaf = async (index, key) => {
      let node = dom.window.document.querySelectorAll(".condition-leaf")[index];
      await select(node.querySelector(".condition-row label:first-child select"), key);
      node = dom.window.document.querySelectorAll(".condition-leaf")[index];
      await select(node.querySelector(".condition-row label:nth-child(3) select"), "true");
    };
    await show(null);
    await click(dom.window.document.querySelector(".condition-add"));
    await setLeaf(0, "C");
    await click([...dom.window.document.querySelectorAll(".condition-group-actions button")].find(button => button.textContent.includes("Добавить группу")));
    assert.equal(current.operator, "AND");
    await select(dom.window.document.querySelector(".condition-group .condition-group > .condition-node-header select"), "OR");
    await setLeaf(1, "A");
    await setLeaf(2, "B");
    await click(dom.window.document.querySelector(".condition-group .condition-group > .condition-node-actions button[aria-label='Выше']"));
    await click(dom.window.document.querySelector(".condition-editor > .condition-group > .condition-group-actions button:first-child"));
    await setLeaf(3, "D");
    assert.deepEqual(current, first, "UI builds (A OR B) AND C AND D");
    await show(null);
    await click(dom.window.document.querySelector(".condition-add"));
    await setLeaf(0, "D");
    await click([...dom.window.document.querySelectorAll(".condition-group-actions button")].find(button => button.textContent.includes("Добавить группу")));
    await select(dom.window.document.querySelector(".condition-group .condition-group > .condition-node-header select"), "OR");
    await setLeaf(1, "A");
    await click(dom.window.document.querySelector(".condition-group .condition-group > .condition-group-actions button:nth-child(2)"));
    await setLeaf(3, "B");
    await setLeaf(4, "C");
    await click(dom.window.document.querySelector(".condition-editor > .condition-group > .condition-children > .condition-group > .condition-children > .condition-leaf:nth-child(2) .condition-remove"));
    await click(dom.window.document.querySelector(".condition-editor > .condition-group > .condition-children > .condition-group > .condition-node-actions button[aria-label='Выше']"));
    assert.deepEqual(current, group("AND", group("OR", leaf("A"), group("AND", leaf("B"), leaf("C"))), leaf("D")), "UI builds (A OR (B AND C)) AND D");
  } finally {
    await act(async () => root.unmount());
    await server.close();
    dom.window.close();
    for (const [key, descriptor] of Object.entries(previous)) descriptor ? Object.defineProperty(globalThis, key, descriptor) : delete globalThis[key];
  }
});
